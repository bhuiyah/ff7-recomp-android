"""Emit src/ffnx_bridge/driver_table.inc: every callback in FFNx's struct ff7_gfx_driver with
its 32-bit offset, measured by compiling FFNx's own ff7.h for x86 (so it cannot drift).

Requires the MSVC x86 environment (source tools/vsenv.sh x86) for clang-cl and windows.h.
usage: py -I tools/ffnx_driver_offsets.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FFNX = os.path.join(ROOT, 'external', 'FFNx', 'src')
BUILD = os.path.join(ROOT, 'build', 'layout')
OUT = os.path.join(ROOT, 'src', 'ffnx_bridge', 'driver_table.inc')


def members():
    text = open(os.path.join(FFNX, 'ff7.h'), encoding='utf-8', errors='replace').read()
    body = re.search(r'struct ff7_gfx_driver\s*\{(.*?)\n\};', text, re.S).group(1)
    return re.findall(r'^\s*(gfx_\w+)\s*\*\s*(\w+)\s*;', body, re.M)


def main():
    ms = members()
    os.makedirs(BUILD, exist_ok=True)
    src = os.path.join(BUILD, 'driver_offsets.cpp')
    with open(src, 'w', encoding='utf-8') as f:
        f.write('#include <windows.h>\n#include <stdint.h>\n#include <stddef.h>\n#include <stdio.h>\n#include "ff7.h"\n')
        f.write('static_assert(sizeof(void*) == 4, "x86");\nint main() {\n')
        f.write('  printf("SIZE %zu\\n", sizeof(struct ff7_gfx_driver));\n')
        for typ, name in ms:
            f.write(f'  printf("{typ} {name} %zu\\n", offsetof(struct ff7_gfx_driver, {name}));\n')
        f.write('  return 0;\n}\n')
    exe = os.path.join(BUILD, 'driver_offsets.exe')
    subprocess.run(['clang-cl', '/nologo', '/std:c++20', '/EHsc', '-m32', '-w', '-I', FFNX, src, '-o', exe], check=True)
    lines = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split('\n')
    size = int(lines[0].split()[1])
    rows = [l.split() for l in lines[1:] if l.strip()]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* AUTO-GENERATED by tools/ffnx_driver_offsets.py from FFNx ff7.h (x86 layout). */\n')
        f.write(f'#define FF7_GFX_DRIVER_SIZE {size}u\n')
        for typ, name, off in rows:
            f.write(f'DRIVER_CB({name}, {typ}, {off})\n')
    print(f'{len(rows)} callbacks, struct size {size} -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
