"""Prove the converted FFNx headers keep 32-bit Windows layouts.

1. Takes the *pristine* game-structure headers from FFNx's git HEAD (before
   tools/ffnx_port.py), compiles a probe for x86 with clang-cl and real windows.h, and
   records sizeof(every game struct) plus offsetof(every gptr/gfn member).
2. Writes src/ffnx_port/layout_asserts.cpp: the same facts as static_asserts, compiled
   for arm64 against the converted headers and shims (part of the FFNx build), so any
   layout drift is a compile error, not memory corruption.

Needs the MSVC x86 environment: source tools/vsenv.sh x86
usage: py -I tools/ffnx_layout_check.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FFNX = os.path.join(ROOT, 'external', 'FFNx')
SRC = os.path.join(FFNX, 'src')
BUILD = os.path.join(ROOT, 'build', 'layout')
PRISTINE = os.path.join(BUILD, 'pristine')
OUT = os.path.join(ROOT, 'src', 'ffnx_port', 'layout_asserts.cpp')
HEADERS = ['common_imports.h', 'common.h', 'ff7.h']
HOST = {'common_externals', 'ff7_externals', 'ff8_externals', 'driver_stats', 'game_mode', 'light_data'}


def git_show(rel):
    return subprocess.run(['git', '-C', FFNX, 'show', f'HEAD:src/{rel}'], check=True,
                          capture_output=True).stdout


def structs_and_members():
    """Struct names (top level, defined) and their converted members, from the converted
    headers (which mark exactly which members became gptr/gfn)."""
    result = {}
    for h in HEADERS:
        text = open(os.path.join(SRC, h), encoding='utf-8', errors='replace').read()
        for m in re.finditer(r'^struct (\w+)\s*\n?\{(.*?)\n\};', text, re.M | re.S):
            name, body = m.group(1), m.group(2)
            if name in HOST or name in result:
                continue
            members = []
            depth = 0
            for line in body.split('\n'):
                code = line.split('//', 1)[0]
                if depth == 0:
                    mm = re.match(r'\s*(?:gptr<.*>|gfn(?:_\w+)?<.*>)\s+(\w+)(\[[^\]]*\])*\s*;', code)
                    if mm:
                        members.append(mm.group(1))
                depth += code.count('{') - code.count('}')
            result[name] = members
    return result


def main():
    os.makedirs(PRISTINE, exist_ok=True)
    for h in HEADERS + ['ff8.h']:
        open(os.path.join(PRISTINE, h), 'wb').write(git_show(h))
    info = structs_and_members()
    probe = os.path.join(BUILD, 'layout_x86.cpp')
    with open(probe, 'w', encoding='utf-8') as f:
        f.write('#include <windows.h>\n#include <stdint.h>\n#include <stddef.h>\n#include <stdio.h>\n')
        f.write('#include "ff7.h"\nstatic_assert(sizeof(void*) == 4, "x86");\nint main() {\n')
        for name, members in info.items():
            f.write(f'  printf("S {name} %zu\\n", sizeof(struct {name}));\n')
            for mem in members:
                f.write(f'  printf("M {name} {mem} %zu\\n", offsetof(struct {name}, {mem}));\n')
        f.write('  return 0;\n}\n')
    exe = os.path.join(BUILD, 'layout_x86.exe')
    # Pristine headers first; the rest of FFNx's includes resolve from its src dir.
    r = subprocess.run(['clang-cl', '/nologo', '/std:c++20', '/EHsc', '-m32', '-w',
                        '-I', PRISTINE, '-I', SRC, probe, '-o', exe], capture_output=True, text=True)
    if r.returncode:
        sys.exit('x86 layout probe failed to build:\n' + r.stdout[-4000:] + r.stderr[-4000:])
    lines = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.splitlines()
    n_s = n_m = 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// AUTO-GENERATED by tools/ffnx_layout_check.py from FFNx\'s pristine headers built\n')
        f.write('// for x86. Every game struct must keep its 32-bit Windows size, and every member\n')
        f.write('// that became gptr/gfn its 32-bit offset. Compiled into the FFNx build.\n')
        f.write('#include <windows.h>\n#include <cstddef>\n#include "ff7.h"\n\n')
        for line in lines:
            p = line.split()
            if p[0] == 'S':
                f.write(f'static_assert(sizeof(struct {p[1]}) == {p[2]}, "layout: sizeof {p[1]}");\n')
                n_s += 1
            else:
                f.write(f'static_assert(offsetof(struct {p[1]}, {p[2]}) == {p[3]}, "layout: {p[1]}.{p[2]}");\n')
                n_m += 1
    print(f'{n_s} struct sizes, {n_m} member offsets -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
