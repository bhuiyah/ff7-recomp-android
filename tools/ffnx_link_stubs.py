"""Generate src/ffnx_port/link_stubs.cpp from the FFNx link census.

The FFNx build leaves out FF8-only code, the Windows crash dialog, DirectInput/WMI
joystick enumeration and (until FFmpeg is built) the movie player. Their symbols are still
referenced (FFNx is one binary for FF7 and FF8; `ff8` is a runtime flag). Each one gets a
definition bound to its exact mangled name with an asm label, so no C++ declaration is
needed:
  functions  stop the run with the symbol's demangled name (never silently return);
  data       zeroed storage (only FF8 / excluded paths touch it, and those never run).

Input: the link log of tools/ffnx_link_probe.sh (built with -Wl,--no-demangle).
usage: py -I tools/ffnx_link_stubs.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG = os.path.join(ROOT, 'build', 'ffnx-link.log')
OUT = os.path.join(ROOT, 'src', 'ffnx_port', 'link_stubs.cpp')
FILT = os.path.join(os.environ.get('LOCALAPPDATA', ''), 'Android', 'Sdk', 'ndk', '28.2.13676358', 'toolchains',
                    'llvm', 'prebuilt', 'windows-x86_64', 'bin', 'llvm-cxxfilt.exe')


def main():
    text = open(LOG, encoding='utf-8', errors='replace').read()
    syms = sorted(set(re.findall(r'undefined symbol: (\S+)', text)))
    if not syms:
        sys.exit('no undefined symbols in the link log')
    dem = subprocess.run([FILT], input='\n'.join(syms), capture_output=True, text=True, check=True).stdout.splitlines()
    funcs, data = [], []
    for m, d in zip(syms, dem):
        if m.startswith('_ZTV') or m.startswith('_ZTI') or m.startswith('_ZTS'):
            data.append((m, d))            # vtables / typeinfo of excluded classes
        elif '(' in d or (m.startswith('_Z') and re.match(r'_ZN?.*E?[A-Za-z0-9_]*$', m) and d != m and '(' in d):
            funcs.append((m, d))
        elif m in DATA_C:
            data.append((m, d))            # C++ globals have unmangled names too (texturePacker)
        elif not m.startswith('_Z'):
            # extern "C" names: decide by a demangled-less heuristic -- functions are what
            # the excluded modules export; FFNx's C-style globals end in nothing callable.
            data.append((m, d)) if m in DATA_C else funcs.append((m, d))
        else:
            data.append((m, d))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// AUTO-GENERATED by tools/ffnx_link_stubs.py from the FFNx link census. Symbols of\n'
                '// FFNx code left out of the Android build (FF8-only, Windows crash dialog, DirectInput\n'
                '// joystick enumeration, the FFmpeg movie player until FFmpeg is built).\n'
                '// Functions stop the run naming themselves; data is zeroed storage.\n'
                '#include <cstdio>\n#include <cstdlib>\n\n'
                '[[noreturn]] static void ffnx_left_out(const char *what) {\n'
                '    std::fprintf(stderr, "[ffnx] STOP: called %s, which is not in the Android build\\n", what);\n'
                '    std::abort();\n}\n\n')
        for i, (m, d) in enumerate(funcs):
            name = d.replace('\\', '\\\\').replace('"', '\\"')
            f.write(f'extern "C" void ffnx_stub_fn_{i}(void) __asm__("{m}");\n'
                    f'extern "C" void ffnx_stub_fn_{i}(void) {{ ffnx_left_out("{name}"); }}\n')
        f.write('\n')
        for i, (m, d) in enumerate(data):
            f.write(f'// {d}\nextern "C" __attribute__((aligned(16))) char ffnx_stub_data_{i}[65536] __asm__("{m}");\n'
                    f'char ffnx_stub_data_{i}[65536];\n')
    print(f'{len(funcs)} function stubs, {len(data)} data stubs -> {os.path.relpath(OUT, ROOT)}')


# Unmangled data symbols in the census: namespace-scope C++ variables are not mangled, so
# they cannot be told from extern "C" functions by name. Listed here from the census.
DATA_C = {'texturePacker', 'g_FF8ZzzArchiveMain', 'g_FF8ZzzArchiveOther'}

if __name__ == '__main__':
    main()
