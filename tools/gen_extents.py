#!/usr/bin/env python3
"""Write generated/recomp/recomp_extents.c: the guest address ranges each lifted function's
body covers.

A lifted function holds every block reachable from its entry, so the same instruction can be
in several of them: code reached by falling through into another function's entry is lifted
inline in the caller as well (sub_00631945 has its own copy of sub_00631AA7's body). A hext
code write that the lift has no variant for must switch every function holding the patched
bytes to the interpreter, not only the nearest entry below it (src/host/ff7_hext.cpp), or the
inline copy keeps running the old code.

Ranges come from the lifter's per-instruction comments (`/* 0x00631AA7: movsx ... */`);
addresses at most 15 bytes apart (an x86 instruction's longest) are one range.

usage: gen_extents.py [generated/recomp] [prefix]
Also run by run_lift.py after a lift.
"""
import os
import re
import sys

FUNC = re.compile(r"^void (\w*?)sub_([0-9A-F]{8})\(void\) \{")
INSN = re.compile(r"/\* 0x([0-9A-F]{8}): ")


def ranges(addrs):
    out = []
    for a in sorted(set(addrs)):
        if out and a - out[-1][1] <= 15:
            out[-1][1] = a
        else:
            out.append([a, a])
    # the end is exclusive and covers the last instruction (at most 15 bytes)
    return [(lo, hi + 15) for lo, hi in out]


def main(outdir="generated/recomp", prefix=""):
    rows = []
    for fn in sorted(os.listdir(outdir)):
        if not (fn.startswith(prefix + "recomp_") and fn.endswith(".c")):
            continue
        if not re.match(re.escape(prefix) + r"recomp_\d{4}\.c$", fn):
            continue
        cur, addrs = None, []
        with open(os.path.join(outdir, fn), encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = FUNC.match(line)
                if m:
                    if cur is not None:
                        rows += [(cur, lo, hi) for lo, hi in ranges(addrs)]
                    cur, addrs = int(m.group(2), 16), []
                    continue
                if cur is not None:
                    addrs += [int(x, 16) for x in INSN.findall(line)]
        if cur is not None:
            rows += [(cur, lo, hi) for lo, hi in ranges(addrs)]
    rows.sort(key=lambda r: (r[1], r[0]))
    path = os.path.join(outdir, f"{prefix}recomp_extents.c")
    with open(path, "w", newline="\n") as fh:
        fh.write("/* AUTO-GENERATED by tools/gen_extents.py: guest ranges each lifted function covers"
                 " (entry, start, end), by start. */\n#include <stdint.h>\n")
        fh.write("typedef struct { uint32_t fn, start, end; } ff7_fn_extent_t;\n")
        fh.write(f"const ff7_fn_extent_t {prefix}ff7_fn_extents[] = {{\n")
        for f, lo, hi in rows:
            fh.write(f"    {{ 0x{f:08X}u, 0x{lo:08X}u, 0x{hi:08X}u }},\n")
        if not rows:
            fh.write("    { 0, 0, 0 },\n")
        fh.write("};\n")
        fh.write(f"const uint32_t {prefix}ff7_fn_extent_count = {len(rows)};\n")
    print(f"[*] {path}: {len(rows)} ranges")


if __name__ == "__main__":
    main(*sys.argv[1:3])
