"""Callee-pop byte counts of lifted functions, for entry overrides.

When FFNx replaces a game function, the replacement runs as a cdecl guest export (it pops
only its return address). If the original function returned with `ret N` (stdcall /
thiscall: the callee pops N bytes of arguments), the override must pop those N bytes too
or the caller's stack is off. This reads every catalogued function's exit blocks from the
exe and records N for the ones that end in `ret imm16` (opcode C2).

Writes generated/recomp/recomp_retn.c: a sorted table {va, pop_bytes} (only N > 0).
usage: py -I tools/gen_retn_table.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, 'analysis', 'catalog.json')
EXE = os.path.join(ROOT, 'game', 'ff7_en.exe')
OUT = os.path.join(ROOT, 'generated', 'recomp', 'recomp_retn.c')
sys.path.insert(0, os.path.join(ROOT, 'external', 'pcrecomp', 'tools', 'pe'))


def main():
    import pefile
    from capstone import Cs, CS_ARCH_X86, CS_MODE_32
    pe = pefile.PE(EXE, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    img = pe.get_memory_mapped_image()
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    cat = json.load(open(CATALOG))
    rows, conflicts = [], 0
    for f in cat['functions']:
        pops = set()
        for start, end, _succ, is_exit in f['blocks']:
            if not is_exit:
                continue
            last = None
            for ins in md.disasm(img[start - base:end - base], start):
                last = ins
            if last is None or last.mnemonic != 'ret':
                continue
            pops.add(int(last.op_str, 0) if last.op_str else 0)
        if not pops:
            continue
        if len(pops) > 1:
            conflicts += 1          # mixed exits: keep the largest, report the count
        n = max(pops)
        if n:
            rows.append((f['address'], n))
    rows.sort()
    with open(OUT, 'w', newline='\n') as fh:
        fh.write('/* AUTO-GENERATED by tools/gen_retn_table.py: callee-popped argument bytes (ret N)\n'
                 ' * of lifted functions, for entry overrides. DO NOT EDIT, DO NOT COMMIT. */\n')
        fh.write('#include <stdint.h>\n')
        fh.write('typedef struct { uint32_t va; uint16_t pop; } recomp_retn_t;\n')
        fh.write('const recomp_retn_t recomp_retn_table[] = {\n')
        for va, n in rows:
            fh.write(f'    {{ 0x{va:08X}u, {n}u }},\n')
        fh.write('    { 0xFFFFFFFFu, 0 } };\n')
        fh.write(f'const uint32_t recomp_retn_count = {len(rows)};\n')
    print(f'{len(rows)} callee-pop functions ({conflicts} with mixed ret forms) -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
